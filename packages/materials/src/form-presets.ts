// Paper's authored presets as form presets (the Glyphfield port, wave 2.3): the shape of each
// preset Paper Shaders 0.0.78 ships for the bound materials (shaders-react dist/shaders/<name>.js,
// Apache-2.0, THIRD_PARTY_NOTICES.md), in the order and under the names Glyphfield's library lists
// them (`PAPER_SHADER_FAMILIES[].presets` and `PAPER_PRESET_BONUS` in its src/lib/liveMaterials.ts,
// the bonus presets first). Turboslide does not depend on @paper-design/shaders-react, where the
// presets live, so their numbers are copied here as data.
//
// Only the shape is kept. Every colour comes from the brand kit (presets.ts) through the palette
// of the preset's ground: `text` (the ink-paper palette: the Text colour as the ground, light
// figures) where Paper drew a dark ground, or light colours on a material that has colours alone;
// `background` (the paper-ink palette) otherwise. Voronoi's Lights and Bubbles and liquid metal's
// Backdrop take `text` by hand, since their figures fill the box. A colour uniform no palette role
// names (FORM_FIGURE_COLOURS) takes the ground palette's second figure colour, so no form preset
// draws a colour outside the kit. A form preset follows a kit change like every palette preset.
//
// Each record keeps only the uniforms that differ from the catalog's defaults (Paper's Default
// preset, which is why Default is not listed), and `from` names Paper's own preset. Labels are in
// sentence case; four read by their form instead of Paper's word (Nintendo Water, 007, Slow-mo,
// Background). A value past the uniform's documented range is clamped to it: smoke ring Cloud's
// noise iterations (10 to 8), waves Groovy's scale and perlin noise Nintendo Water's and Moss's (5,
// 5 and 6.67 to 4). Liquid metal's Noir and gem smoke's Fire keep the recorded presets of those
// names (presets.ts). Water's Abstract and Streaming are left out: they draw no light of their own
// and only bend a source picture, which a shader block has none of. Browser safe; data only.
import type { MaterialUniforms } from '@turboslide/schema/blocks/material';

/** One form preset: its name and label, Paper's preset it came from, its ground and its shape. */
export type FormPreset = {
  name: string;
  label: string;
  /** Paper's own name for the preset (shaders-react). */
  from: string;
  /** The kit role whose palette preset gives the colours: Text (ink-paper) or Background (paper-ink). */
  ground: 'text' | 'background';
  /** The shape uniforms that differ from the catalog's defaults; no colour. */
  uniforms: MaterialUniforms;
};

