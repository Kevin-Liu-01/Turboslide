#!/usr/bin/env node
// Generates packages/render/src/blocks/equation-css.ts from Temml's own stylesheet (gslides-parity
// SPEC-5 8.1: "Temml-Local.css is scoped by the renderer"). Every selector of
// node_modules/temml/dist/Temml-Local.css is prefixed with the sheet root and the equation
// block's class, so a `math` element outside an equation block (there is none: the equation
// renderer is the one writer of `<math>`) and the chrome are untouched; the `@font-face` of the
// 9 KB Temml supplement keeps its descriptor with the `url()` replaced by a placeholder the
// runtime fills (a data URI in Node, a Vite asset URL in the studio). Run once per Temml
// version and commit the output; the check chain never runs it:
//
//   node packages/render/scripts/build-equation-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(HERE, '..', 'package.json'));
const temmlPackage = require.resolve('temml/package.json');
const version = JSON.parse(readFileSync(temmlPackage, 'utf8')).version;
const css = readFileSync(join(dirname(temmlPackage), 'dist', 'Temml-Local.css'), 'utf8');

export const SCOPE = '.ts-sheet .equation';
export const TEMML_WOFF2_TOKEN = '__TEMML_WOFF2__';

/** Splits a stylesheet into top level rules: `{ selector, body }` for a style rule, `{ at, body }` for an at rule. */
export function splitRules(source) {
  const text = source.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules = [];
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open === -1) break;
    const prelude = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === '{') depth += 1;
      else if (text[j] === '}') depth -= 1;
      j += 1;
    }
    const body = text.slice(open + 1, j - 1).trim();
    if (prelude.startsWith('@')) rules.push({ at: prelude, body });
    else if (prelude !== '') rules.push({ selector: prelude, body });
    i = j;
  }
  return rules;
}

/** One selector list scoped under the equation root; `math` itself becomes the root's `math`. */
export function scopeSelector(selector) {
  return selector
    .split(',')
    .map((part) => part.trim())
    .filter((part) => part !== '')
    .map((part) => `${SCOPE} ${part}`)
    .join(', ');
}

export function scopeStylesheet(source) {
  const out = [];
  for (const rule of splitRules(source)) {
    if (rule.at !== undefined) {
      if (rule.at === '@font-face') {
        out.push(
          `@font-face { ${rule.body.replace(/url\([^)]*\)/, `url(${TEMML_WOFF2_TOKEN})`).replace(/\s+/g, ' ')} }`,
        );
        continue;
      }
      // a nested at rule (media, supports): scope the rules inside it
      out.push(`${rule.at} { ${scopeStylesheet(rule.body)} }`);
      continue;
    }
    out.push(`${scopeSelector(rule.selector)} { ${rule.body.replace(/\s+/g, ' ')} }`);
  }
  return out.join('\n');
}

const scoped = scopeStylesheet(css);
const output = `// Generated by packages/render/scripts/build-equation-css.mjs from temml ${version}
// dist/Temml-Local.css (MIT, THIRD_PARTY_NOTICES.md "Temml"); every selector scoped under
// \`${SCOPE}\` and the supplement font's url replaced by \`${TEMML_WOFF2_TOKEN}\`, which
// blocks/equation.ts fills. Do not edit by hand: rerun the script after a Temml upgrade.
export const TEMML_VERSION = ${JSON.stringify(version)};
export const EQUATION_SCOPE = ${JSON.stringify(SCOPE)};
export const TEMML_WOFF2_TOKEN = ${JSON.stringify(TEMML_WOFF2_TOKEN)};
export const TEMML_SCOPED_CSS = ${JSON.stringify(scoped)};
`;
writeFileSync(join(HERE, '..', 'src', 'blocks', 'equation-css.ts'), output);
console.log(`equation-css.ts written from temml ${version}: ${scoped.length} characters`);
