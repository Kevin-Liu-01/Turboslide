// ---- raster helpers ----------------------------------------------------------------------
function tile({ size, markPx, N, ink, ground, transparent = false }) {
  const cell = markPx / N;
  if (!Number.isInteger(cell)) throw new Error(`non integer cell ${markPx}/${N}`);
  const off = (size - markPx) / 2;
  const ch = 4;
  const data = Buffer.alloc(size * size * ch);
  const { bits } = markBits(N);
  for (let y = 0; y < size; y++)
    for (let x = 0; x < size; x++) {
      const i = (y * size + x) * ch;
      let c = ground,
        a = transparent ? 0 : 255;
      const mx = x - off,
        my = y - off;
      if (mx >= 0 && my >= 0 && mx < markPx && my < markPx) {
        const cx = Math.floor(mx / cell),
          cy = Math.floor(my / cell);
        if (bits[cy * N + cx]) {
          c = ink;
          a = 255;
        }
      }
      data[i] = c[0];
      data[i + 1] = c[1];
      data[i + 2] = c[2];
      data[i + 3] = a;
    }
  return sharp(data, { raw: { width: size, height: size, channels: 4 } });
}
