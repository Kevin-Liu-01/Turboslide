// ---- favicon.ico: three 32 bit BMP entries with AND masks (report 02 section 6.3) ----------
async function icoEntry(size) {
  const { data } = await sharp(join(ICONS, `favicon-${size}.png`))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const rowBytes = size * 4;
  const maskRow = Math.ceil(size / 32) * 4;
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(size, 4);
  header.writeInt32LE(size * 2, 8);
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(0, 16);
  header.writeUInt32LE(rowBytes * size + maskRow * size, 20);
  const pixels = Buffer.alloc(rowBytes * size);
  for (let y = 0; y < size; y++) {
    const src = (size - 1 - y) * rowBytes;
    for (let x = 0; x < size; x++) {
      const s = src + x * 4,
        d = y * rowBytes + x * 4;
      pixels[d] = data[s + 2];
      pixels[d + 1] = data[s + 1];
      pixels[d + 2] = data[s];
      pixels[d + 3] = data[s + 3];
    }
  }
  const mask = Buffer.alloc(maskRow * size, 0);
  return Buffer.concat([header, pixels, mask]);
}
{
  const entries = [];
  for (const s of [16, 32, 48]) entries.push([s, await icoEntry(s)]);
  const head = Buffer.alloc(6);
  head.writeUInt16LE(0, 0);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(entries.length, 4);
  const dir = Buffer.alloc(16 * entries.length);
  let offset = 6 + dir.length;
  const bodies = [];
  entries.forEach(([s, body], i) => {
    const o = i * 16;
    dir[o] = s;
    dir[o + 1] = s;
    dir[o + 2] = 0;
    dir[o + 3] = 0;
    dir.writeUInt16LE(1, o + 4);
    dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(body.length, o + 8);
    dir.writeUInt32LE(offset, o + 12);
    offset += body.length;
    bodies.push(body);
  });
  writeFileSync(join(ICONS, 'favicon.ico'), Buffer.concat([head, dir, ...bodies]));
}

