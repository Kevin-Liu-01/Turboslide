// Writes brand-c/mock/data.js: the product's own glyphs and marks for the static mockups, read from the tree
// (packages/chrome/src/icons.tsx through icons.json, packages/theme/src/brand.ts, packages/theme/src/sprite.ts), so a
// mockup draws nothing the product would not.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../../..');
const icons = JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8'));
const brand = await import(join(root, 'packages/theme/src/brand.ts'));
const sprite = readFileSync(join(root, 'packages/theme/src/sprite.ts'), 'utf8');
const gt = /'gt-mark': \{\s*id: 'gt-mark',\s*viewBox: '([^']+)',\s*body: '([^']+)'/.exec(sprite);
if (!gt) throw new Error('gt-mark not found');

const used = [
  'search', 'plus', 'chevron-down', 'chevron-up', 'arrow-uturn-left', 'arrow-uturn-right', 'printer', 'paint-brush',
  'cursor-arrow', 'photo', 'square-2-stack', 'minus', 'chat', 'chat-bubble-left', 'play', 'lock-closed', 'bars-3',
  'bars-3-bottom-right', 'ellipsis-vertical', 'ellipsis-horizontal', 'close', 'clock', 'cloud', 'arrow-down-tray',
  'command-line', 'squares-2x2', 'queue-list', 'information-circle', 'user-circle', 'check', 'sidebar', 'document-plus',
  'presentation-chart-line', 'sun', 'moon', 'computer-desktop', 'language', 'arrows-up-down', 'cursor-arrow-rays',
];
const pick = {};
for (const name of used) {
  if (!icons[name]) throw new Error(`no icon ${name}`);
  pick[name] = icons[name];
}
const outlines = readFileSync(join(root, 'packages/theme/brand/wordmark-outlines.svg'), 'utf8');
const word = [...outlines.matchAll(/<path transform="([^"]+)"[^>]*? d="([^"]+)"/g)].find((m) => m[1].includes('0.0322265625'));
if (!word) throw new Error('word outline not found');
const data = {
  word: { transform: word[1], d: word[2] },
  icons: pick,
  mark: {
    solid: brand.markPath(2),
    cells32: brand.cellRects(brand.markBits(32)),
    cells64: brand.cellRects(brand.markBits(64)),
  },
  gtMark: { viewBox: gt[1], body: gt[2] },
};
writeFileSync(join(here, '../mock/data.js'), `/* Generated by brand-c/tools/build-mock-data.mjs from the tree; do not edit. */\nwindow.C_DATA = ${JSON.stringify(data)};\n`);
console.log('icons', Object.keys(pick).length, 'gt viewBox', gt[1]);
