// The generated pages of the docs at /docs (docs/POLISH-2.md 5.3, 5.4): the action reference, one
// MDX page per action group with an index of the groups, and the deck grammar's page, written by
// `pnpm generate:contracts` beside the other contracts under apps/studio/content/docs. Every
// count is read from the contracts this generator writes in the same run (manifest.json,
// cli.json, mcp-tools.json, openapi.json and describe.json), so no page types a number. Plain
// text in the pages is escaped for MDX; code spans are kept as written.
import { ACTION_GROUPS, actionsInOrder } from '@turboslide/schema/actions';
import type { ActionGroup } from '@turboslide/schema/actions';
import {
  BLOCK_GROUPS,
  CATALOG,
  LAYOUT_CATALOG,
  SLIDE_KIND_CATALOG,
} from '@turboslide/schema/catalog';
import { SHEET_HEIGHT, SHEET_WIDTH } from '@turboslide/schema/render';
import { generateCli } from './cli.ts';
import { generateDescribe } from './describe.ts';
import { markdownTable, summarizeProperties, toJsonSchema } from './json-schema.ts';
import { generateManifest } from './manifest.ts';
import { generateMcpTools } from './mcp.ts';
import { generateOpenApi } from './openapi.ts';

/** The docs' content folder, from the repository's root. */
export const DOCS_CONTENT_DIR = 'apps/studio/content/docs';

const GENERATED = (from: string): string =>
  `# Generated by pnpm generate:contracts (packages/agent/src/generate/docs.ts) from ${from}; do not edit by hand.`;

/** The reader's name of each action group, the page title's first words. */
export const GROUP_TITLES: Readonly<Record<ActionGroup, string>> = {
  deck: 'Presentations',
  slide: 'Slides',
  block: 'Objects on a slide',
  asset: 'Pictures and files',
  render: 'Renders',
  lint: 'Checks',
  version: 'Versions',
  export: 'Downloads',
  view: 'The view',
  studio: 'The studio page',
  presence: 'Presence',
  sync: 'Sync',
  comment: 'Comments',
  share: 'Sharing',
  account: 'Accounts',
  admin: 'Administration',
};

/**
 * Text for an MDX page: the characters MDX reads as code (`<`, `{`, `}`) and the emphasis marks
 * (`*`, `_`) escaped outside code spans. A table cell's pipes are escaped by `markdownTable`.
 */
export function mdxText(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((part) =>
      part.startsWith('`') && part.endsWith('`') && part.length > 1
        ? part
        : part
            .replace(/[<>{}*]/g, (char) => `\\${char}`)
            /* an underscore inside a word starts no emphasis and stays bare, as prettier writes it */
            .replace(/(?<![A-Za-z0-9])_|_(?![A-Za-z0-9])/g, '\\_'),
    )
    .join('');
}

/** Which transports carry each action, read from the contracts generated in this run. */
export type TransportFacts = {
  total: number;
  cli: Set<string>;
  mcp: Map<string, string>;
  http: Set<string>;
  window: Set<string>;
  usage: Map<string, string>;
};

/** The five generated contracts the reference reads its facts from. */
export type Contracts = {
  cli: ReturnType<typeof generateCli>;
  mcp: ReturnType<typeof generateMcpTools>;
  describe: ReturnType<typeof generateDescribe>;
  openapi: ReturnType<typeof generateOpenApi>;
  manifest: ReturnType<typeof generateManifest>;
};

export function transportFacts(contracts: Contracts): TransportFacts {
  const openapi = contracts.openapi as { paths?: Record<string, unknown> };
  const describe = contracts.describe as { actions?: unknown };
  const http = new Set(
    Object.keys(openapi.paths ?? {})
      .filter((path) => path.startsWith('/api/actions/') && !path.includes('{'))
      .map((path) => path.slice('/api/actions/'.length)),
  );
  const windowIds = Array.isArray(describe.actions)
    ? describe.actions.filter((id): id is string => typeof id === 'string')
    : [];
  return {
    total: contracts.manifest.actionCount,
    cli: new Set(contracts.cli.actions.map((action) => action.action)),
    mcp: new Map(contracts.mcp.tools.map((tool) => [tool.action, tool.name])),
    http,
    window: new Set(windowIds),
    usage: new Map(contracts.cli.actions.map((action) => [action.action, action.usage])),
  };
}

/** One sentence with the count of actions on each transport, for the reference's head. */
function countsSentence(facts: TransportFacts, ids: ReadonlyArray<string>, whole: boolean): string {
  const on = (set: Set<string> | Map<string, string>): number =>
    ids.filter((id) => set.has(id)).length;
  const total = whole ? facts.total : ids.length;
  return `<ActionCounts total="${total}" cli="${on(facts.cli)}" mcp="${on(facts.mcp)}" http="${on(facts.http)}" window="${on(facts.window)}" />`;
}

function fieldRows(input: Parameters<typeof toJsonSchema>[0]): string[][] {
  const schema = toJsonSchema(input);
  if (schema.type !== 'object') return [];
  return summarizeProperties(schema).map((property) => [
    `\`${property.name}\``,
    /* a long list of values (the 24 reaction emoji) reads as its count */
    (property.enumValues?.length ?? 0) > 6
      ? `one of ${property.enumValues?.length} values`
      : mdxText(property.type),
    property.required ? 'yes' : 'no',
    mdxText(property.description ?? property.title ?? ''),
  ]);
}

function actionSection(
  spec: ReturnType<typeof actionsInOrder>[number],
  facts: TransportFacts,
): string {
  const rows = fieldRows(spec.input);
  const usage = facts.usage.get(spec.id);
  const tool = facts.mcp.get(spec.id);
  const carried = [
    facts.cli.has(spec.id) ? 'command line' : null,
    facts.mcp.has(spec.id) ? 'MCP' : null,
    facts.http.has(spec.id) ? 'HTTP' : null,
    facts.window.has(spec.id) ? 'page' : null,
  ].filter((name): name is string => name !== null);
  return [
    `## ${spec.id} [#${spec.id}]`,
    '',
    `**${mdxText(spec.label)}.** ${mdxText(spec.doc)}`,
    '',
    rows.length === 0
      ? 'It takes no input.'
      : markdownTable(['Field', 'Type', 'Required', 'Description'], rows),
    '',
    `- Command line: ${usage === undefined ? 'No CLI command.' : `\`${usage}\``}`,
    `- MCP tool: ${tool === undefined ? 'No MCP tool.' : `\`${tool}\``}`,
    `- HTTP: ${facts.http.has(spec.id) ? `\`POST /api/actions/${spec.id}\`` : 'No HTTP endpoint.'}`,
    `- Runs on: ${carried.length === 0 ? 'no transport yet' : carried.join(', ')}.`,
    `- Changes the presentation: ${spec.mutates ? (rows.some((row) => row[0] === '`baseRevision`') ? 'yes; send the `baseRevision` you read' : 'yes') : 'no'}.`,
  ].join('\n');
}

function groupTitle(group: ActionGroup): string {
  return GROUP_TITLES[group];
}

/** The reference pages: the index, its meta.json and one page per action group. */
export function generateDocsReference(
  contracts: Contracts = {
    cli: generateCli(),
    mcp: generateMcpTools(),
    describe: generateDescribe(),
    openapi: generateOpenApi(),
    manifest: generateManifest(),
  },
): Record<string, string> {
  const facts = transportFacts(contracts);
  const specs = actionsInOrder();
  const dir = `${DOCS_CONTENT_DIR}/reference`;
  const groups = ACTION_GROUPS.filter((group) => specs.some((spec) => spec.group === group));
  const out: Record<string, string> = {};
  const indexRows = groups.map((group) => {
    const ids = specs.filter((spec) => spec.group === group).map((spec) => spec.id);
    const on = (set: Set<string> | Map<string, string>): string =>
      String(ids.filter((id) => set.has(id)).length);
    return [
      `[${groupTitle(group)}](/docs/reference/${group})`,
      String(ids.length),
      on(facts.cli),
      on(facts.mcp),
      on(facts.http),
      on(facts.window),
    ];
  });
  out[`${dir}/index.mdx`] = [
    '---',
    GENERATED('packages/schema/src/actions.ts and the contracts in packages/agent/generated'),
    'title: Action reference',
    'description: Every action of Turboslide by group, with its input fields and its name on the command line, over MCP and over HTTP.',
    '---',
    '',
    'Every operation in Turboslide is one action in one table. The command line, the MCP tools, the HTTP endpoints and the page API are made from that table, and each one carries the actions listed here.',
    '',
    countsSentence(
      facts,
      specs.map((spec) => spec.id),
      true,
    ),
    '',
    '## Groups',
    '',
    markdownTable(['Group', 'Actions', 'Command line', 'MCP', 'HTTP', 'Page'], indexRows),
    '',
    'Each action changes a presentation only with `baseRevision`, the revision it read; see [Agents](/docs/agents) for the rules every call follows. The OpenAPI document of every HTTP endpoint is at [/openapi.json](/openapi.json).',
    '',
  ].join('\n');
  out[`${dir}/meta.json`] =
    `${JSON.stringify({ title: 'Action reference', pages: groups }, null, 2)}\n`;
  for (const group of groups) {
    const inGroup = specs.filter((spec) => spec.group === group);
    out[`${dir}/${group}.mdx`] = [
      '---',
      GENERATED('packages/schema/src/actions.ts and the contracts in packages/agent/generated'),
      `title: ${groupTitle(group)}`,
      `description: The ${inGroup.length === 1 ? 'action' : 'actions'} of the ${group} group, with their input fields and their names on every transport.`,
      '---',
      '',
      countsSentence(
        facts,
        inGroup.map((spec) => spec.id),
        false,
      ),
      '',
      inGroup.map((spec) => actionSection(spec, facts)).join('\n\n'),
      '',
    ].join('\n');
  }
  return out;
}

/** The deck grammar's page: the sheet, the slide kinds, the layouts and the blocks by group. */
export function generateDocsGrammar(): Record<string, string> {
  const kinds = Object.entries(SLIDE_KIND_CATALOG).map(([kind, entry]) => [
    `\`${kind}\``,
    mdxText(entry.label),
    mdxText(entry.doc),
  ]);
  const layouts = Object.entries(LAYOUT_CATALOG).map(([layout, entry]) => [
    `\`${layout}\``,
    mdxText(entry.label),
    mdxText(entry.doc),
  ]);
  const blocks = BLOCK_GROUPS.map((group) => {
    const rows = Object.values(CATALOG)
      .filter((entry) => entry.group === group.id)
      .map((entry) => [`\`${entry.type}\``, mdxText(entry.label), mdxText(entry.doc)]);
    return rows.length === 0
      ? ''
      : [
          `### ${mdxText(group.label)}`,
          '',
          markdownTable(['Type', 'Name', 'What it is'], rows),
          '',
        ].join('\n');
  }).filter((part) => part !== '');
  return {
    [`${DOCS_CONTENT_DIR}/agents/grammar.mdx`]: [
      '---',
      GENERATED('packages/schema/src/catalog.ts'),
      'title: Deck grammar',
      'description: How a slide is written as data, with the slide kinds, the layouts and the block types an agent writes.',
      '---',
      '',
      `A slide is a kind, a layout and typed blocks in named slots, on a sheet of ${SHEET_WIDTH} by ${SHEET_HEIGHT} pixels. An agent writes the document, not the pixels: there are no coordinates except on the freeform layout. The validator refuses a slide that breaks the schema, and the grammar linter reports the rules a slide breaks.`,
      '',
      '## Slide kinds',
      '',
      markdownTable(['Kind', 'Name', 'What it is'], kinds),
      '',
      '## Layouts',
      '',
      markdownTable(['Layout', 'Name', 'What it is'], layouts),
      '',
      '## Blocks',
      '',
      ...blocks,
      'The full grammar, with every field of every block and every lint rule, is in [/llms-full.txt](/llms-full.txt).',
      '',
    ].join('\n'),
  };
}
